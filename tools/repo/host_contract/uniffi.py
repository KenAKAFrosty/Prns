def secret_input_types(schema):
    """Propagate input-only ownership through the semantic graph, not a field list."""
    vocabulary = session_vocabulary(schema)
    secret = {item['name'] for item in vocabulary['fixedBytes'] if item.get('secret')}
    if secret != {'IdentitySecret'}:
        raise ValueError("secret types require an explicit zeroizing Rust owner mapping")
    def name(t):
        return name(t['array']) if isinstance(t, dict) else t
    changed = True
    while changed:
        changed = False
        for item in vocabulary['records'] + vocabulary['unions']:
            fields = item.get('fields', [field for case in item.get('cases', []) for field in case['fields']])
            if item['name'] not in secret and any(name(field['type']) in secret for field in fields):
                secret.add(item['name'])
                changed = True
    return secret - {'IdentitySecret'}


