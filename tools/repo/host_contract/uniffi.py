    known = records.keys() | unions.keys() | enums.keys()
    fingerprint = hashlib.sha256(json.dumps(schema, sort_keys=True, separators=(',', ':')).encode()).hexdigest()

    def core(name):
        return 'prns_host::' + CORE_NAMES.get(name, name)

    def typ(t):
        if isinstance(t, dict): return f"Vec<{typ(t['array'])}>"
        if t in fixed: return 'IdentitySecretInput' if fixed[t].get('secret') else 'Vec<u8>'
        return {'bytes': 'Vec<u8>', 'string': 'String', 'u128': 'WideCounter',
                'ResourceStream': 'ResourceDescriptor', **scalar}.get(t, t)

    def field_type(f):
        t = typ(f['type'])
        return f'Option<{t}>' if f.get('optional') else t

    def convert(t, expr, reverse=False):
        if isinstance(t, dict):
            inner = convert(t['array'], 'item', reverse)
            if inner == 'item': return expr
            if reverse: return f'{expr}.into_iter().map(|item| Ok({inner})).collect::<Result<Vec<_>, BindingError>>()?'
            return f'{expr}.into_iter().map(|item| {inner}).collect()'
        if t in fixed:
            if reverse:
                if t == 'IdentitySecret': return f'{expr}.into_core()'
                return f'{core(t)}::new(fixed_bytes::<{fixed[t]["length"]}>({expr}, "{t}")?)'
            return f'{expr}.into_bytes().to_vec()'
        if t == 'safeUint': return f'safe_uint({expr})?' if reverse else expr
        if t == 'safeInt': return f'safe_int({expr})?' if reverse else expr
        if t == 'u128': return f'{expr}.into()'
        if t in known:
            return f'{expr}.try_into()?' if reverse and t not in enums else f'{expr}.into()'
        return expr

    def conv_field(f, expr, reverse=False):
        if f.get('optional'):
            inner = convert(f['type'], 'item', reverse)
            if inner == 'item': return expr
            if reverse: return f'{expr}.map(|item| Ok({inner})).transpose()?'
            return f'{expr}.map(|item| {inner})'
