def coverage(schema, extensions=None):
    vocabulary = session_vocabulary(schema)
    projections = {}
    def project(names, target, status="projected"):
        for name in names.split():
            projections[name] = {"status": status, "target": target}
    project("contractInfo", "bindingContract: semantic fingerprint and package version")
    project("backendInfo", "backendInfo")
    project("hostCreate hostRelease hostStop", "Owned HostSession open/stop/nonblocking finalization")
    project("hostLifecycle", "Host.lifecycle")
    project("hostSnapshot hostSnapshotRead hostSnapshotRelease", "Host.snapshot async owned value")
    project("hostIdentityHash", "Host.identityHash")
    project("hostDestinationCount hostDestinationHash", "Host.destinationHashes owned array")
    project("hostAttachSuppliedPipe suppliedPipeClaimAttachment suppliedPipeNextOpenRequest suppliedPipeRegisterReadiness suppliedPipeInterruptWait suppliedPipeRelease suppliedPipeOpenRequestProvide suppliedPipeOpenRequestDecline suppliedPipeOpenRequestRelease", "Rust prepared transport embedding; no foreign file descriptor ownership API", "native-embedding-only")
    project("hostBeginResourceUpload", "Host.beginResourceUpload")
    project("resourceUploadWrite resourceUploadIsWritable", "ResourceUpload.writeChunk async readiness/admission")
    project("resourceUploadFinish", "ResourceUpload.finish")
    project("resourceUploadAbort resourceUploadRelease", "ResourceUpload.abort/nonblocking finalization")
    project("commandWait commandRegisterReadiness commandInterruptWait commandRelease", "Host.execute foreign future; wait cancellation does not cancel accepted command")
    project("hostClaimApplicationEvents hostClaimDiagnostics", "Host.applicationEvents/diagnostics single-consumer leases")
    project("eventStreamRegisterReadiness eventStreamInterruptWait readinessRegistrationRelease", "EventStream.ready non-consuming cancellable future")
    project("eventStreamRelease", "EventStream.close/nonblocking finalization")
    project("eventStreamNext", "EventStream.tryNext bounded nonblocking transfer")
    project("eventRelease eventKind eventBytes eventString eventU64 eventU128", "Generated typed HostEvent value with exact scalar conversions")
    project("eventResourceStream", "Owned ResourceReader alongside ApplicationEvent resource descriptor")
    project("resourceStreamRelease resourceStreamNext", "ResourceReader.readChunk/close/nonblocking finalization")
    names = {v['name'] for v in schema['operations']}
    if names != projections.keys():
        raise ValueError(f"UniFFI operation projection coverage drift: missing={names - projections.keys()}, stale={projections.keys() - names}")
    result = {'records':[v['name'] for v in vocabulary['records']],
              'unions':{v['name']:[c['name'] for c in v['cases']] for v in vocabulary['unions']},
              'rawOperations':projections,
              'commands':schema['commandProjection']['outcomes'],
              'inputOnly': sorted(secret_input_types(schema)),
              'resourceHandle': 'Session-scoped ResourceDescriptor, resolved by owning session; never a raw pointer',
              'diagnosticsDropped': 'Synthetic DiagnosticBatch overflow item with exact two-u64 counter'}
    if extensions is not None:
        result['nativeExtensions'] = extensions
    return json.dumps(result,indent=2)+'\n'


