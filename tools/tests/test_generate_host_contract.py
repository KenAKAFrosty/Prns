    def test_registered_inputs_cover_actual_generator_reads_and_outputs(self):
        import sys
        import tomllib
        from unittest.mock import patch

        registry = tomllib.loads((ROOT / 'validation/manifest.toml').read_text())
        suite = next(row for row in registry['suite'] if row['id'] == 'host-contract-generated')
        inputs = [(ROOT / value).resolve() for value in suite['inputs']]
        reads, outputs = set(), set()
        original_read_text = Path.read_text

        def read_text(path, *args, **kwargs):
            resolved = path.resolve()
            if resolved.is_relative_to(ROOT):
                reads.add(resolved)
            return original_read_text(path, *args, **kwargs)

        def capture_output(path, _content, _check):
            outputs.add(path.resolve())

        # Exercise the actual generator and high-level verification while
        # replacing its only output writer. No generated bytes are modified.
        with patch.object(Path, 'read_text', read_text), \
                patch.object(GENERATOR, 'write_or_check', capture_output), \
                patch.object(sys, 'argv', ['generate-host-contract.py', '--check']):
            GENERATOR.main()

        self.assertTrue(reads)
        self.assertTrue(outputs)
        for path in sorted(reads | outputs):
            with self.subTest(path=path.relative_to(ROOT)):
                self.assertTrue(any(path == item or path.is_relative_to(item) for item in inputs),
                                f'unregistered generator input/output: {path.relative_to(ROOT)}')
        self.assertIn(ROOT / 'prns-host/bindings/uniffi/typescript/host-adapter.generated.ts', outputs)
        self.assertFalse(any(path.is_relative_to(ROOT / 'prns-react-native') for path in outputs))
        self.assertFalse(any(value.startswith('prns-react-native/') for value in suite['inputs']))

