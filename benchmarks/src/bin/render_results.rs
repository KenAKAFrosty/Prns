    #[test]
    fn aggregates_medians_maximums_and_three_sample_energy() {
        let mut rows = Vec::new();
        for (sample, rate, rss, energy) in [
            (0, 10.0, 100.0, 3.0),
            (1, 30.0, 300.0, 1.0),
            (2, 20.0, 200.0, 2.0),
        ] {
            rows.push(row(
                sample,
                Axis::Throughput,
                "delivered_per_sec",
                Some(rate),
            ));
            rows.push(row(
                sample,
                Axis::Memory,
                "initiator_peak_rss_bytes",
                Some(rss),
            ));
            rows.push(row(
                sample,
                Axis::Energy,
                "net_millijoules_per_delivered",
                Some(energy),
            ));
            rows.push(row(sample, Axis::Conformance, "settled_clean", Some(1.0)));
        }
        let aggregates = aggregate(&rows);
        assert_eq!(
            aggregates[0].median(Axis::Throughput, "delivered_per_sec"),
            Some(20.0)
        );
        assert_eq!(
            aggregates[0].maximum(Axis::Memory, "initiator_peak_rss_bytes"),
            Some(300.0)
        );
        assert_eq!(aggregates[0].energy(), Some(2.0));
        assert_eq!(aggregates[0].conformant(), Some(true));
    }

