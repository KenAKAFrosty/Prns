use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use benchmarks::{
    load_all_rows, load_catalog, load_host, load_implementations, scenario_dir, Axis,
    ImplementationDescriptor, ImplementationRole, ResultRow, ScenarioCellNote, ScenarioTopology,
    Subject, RESULT_SCHEMA_VERSION,
};

const PASS_ICON: &str = r#"<img src="assets/check.svg" width="14" alt="conformant" />"#;
const FAIL_ICON: &str = r#"<img src="assets/cross.svg" width="14" alt="non-conformant" />"#;
fn main() {
    let files = render_all();
    if std::env::args().any(|argument| argument == "--check") {
        let stale: Vec<&PathBuf> = files
            .iter()
            .filter(|(path, body)| std::fs::read_to_string(path).unwrap_or_default() != *body)
            .map(|(path, _)| path)
            .collect();
        if stale.is_empty() {
            println!("results tables: IN SYNC ({} files)", files.len());
            return;
        }
        eprintln!("results tables: STALE — regenerate with `cargo benchmark --publish`:");
        for path in stale {
            eprintln!("  {}", path.display());
        }
        std::process::exit(1);
    }
    for (path, body) in &files {
        std::fs::write(path, body)
            .unwrap_or_else(|error| panic!("write {}: {error}", path.display()));
    }
    eprintln!("wrote {} result files", files.len());
}

fn bench_dir() -> PathBuf {
    std::env::var_os("BENCHMARK_RENDER_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).to_path_buf())
}

fn render_all() -> Vec<(PathBuf, String)> {
    let implementations = load_implementations();
    let mut by_host: BTreeMap<String, Vec<ResultRow>> = BTreeMap::new();
    for row in load_all_rows() {
        assert_eq!(
            row.schema_version, RESULT_SCHEMA_VERSION,
            "{} still uses result schema v{}",
            row.scenario, row.schema_version
        );
        if Manifest::exists(&row.scenario) {
            by_host.entry(row.host.clone()).or_default().push(row);
        }
    }

    let mut files = Vec::new();
    let mut hosts = Vec::new();
    for (host, rows) in &by_host {
        files.push((
            bench_dir().join(format!("RESULTS-{host}.md")),
            render_host(host, rows, &implementations),
        ));
        hosts.push((host.clone(), machine_label(host)));
    }
    files.push((bench_dir().join("RESULTS.md"), render_index(&hosts)));
    files
}

fn machine_label(host: &str) -> String {
    load_host(host)
        .and_then(|descriptor| descriptor.cpu_model)
        .unwrap_or_else(|| "—".to_string())
}

fn render_index(hosts: &[(String, String)]) -> String {
    let mut out = String::from(
        "<!-- Generated by `cargo benchmark --publish`. Do not edit by hand. -->\n\n\
         # Benchmark results\n\n\
         | Host | Machine | Results |\n|---|---|---|\n",
    );
    for (host, machine) in hosts {
        let _ = writeln!(out, "| `{host}` | {machine} | [view](RESULTS-{host}.md) |");
    }
    out
}

fn render_host(
    host: &str,
    rows: &[ResultRow],
    implementations: &[ImplementationDescriptor],
) -> String {
    let mut out = format!("# Benchmark results — `{host}`\n\n[← All hosts](RESULTS.md)\n");
    render_qualification(&mut out, rows);
    render_machine_and_method(&mut out, host);

    let aggregates = aggregate(rows);
    render_headline(
        &mut out,
        &aggregates,
        implementations,
        qualification_complete(&aggregates),
    );

    let mut grouped: BTreeMap<String, Vec<(Manifest, Vec<&Aggregate>)>> = BTreeMap::new();
    let mut by_scenario: BTreeMap<String, Vec<&Aggregate>> = BTreeMap::new();
    for aggregate in &aggregates {
        by_scenario
            .entry(aggregate.scenario.clone())
            .or_default()
            .push(aggregate);
    }
    for (scenario, subject_rows) in by_scenario {
        let manifest = Manifest::load(&scenario);
        grouped
            .entry(manifest.category.clone())
            .or_default()
            .push((manifest, subject_rows));
    }

    out.push_str("\n## Detailed results\n");
    for (category, mut scenarios) in grouped {
        scenarios.sort_by(|a, b| a.0.title.cmp(&b.0.title));
        let _ = write!(out, "\n### {category}\n");
        for (manifest, subject_rows) in scenarios {
            render_scenario(&mut out, &manifest, &subject_rows, implementations);
        }
    }
    render_legends(&mut out, &aggregates, implementations);
    out
}

fn render_qualification(out: &mut String, rows: &[ResultRow]) {
    let aggregates = aggregate(rows);
    let complete = qualification_complete(&aggregates);
    let commits = rows
        .iter()
        .map(|row| row.commit.as_str())
        .collect::<BTreeSet<_>>();
    let commit = (commits.len() == 1)
        .then(|| commits.first().copied())
        .flatten()
        .unwrap_or("mixed source commits");
    let clean = rows.iter().all(|row| {
        row.provenance
            .get("source_dirty")
            .is_some_and(|value| value == "false")
    });
    let status = if complete && clean && commit.len() == 40 {
        "COMPLETE"
    } else {
        "INCOMPLETE"
    };
    let conformant_samples = aggregates
        .iter()
        .map(|item| {
            item.values(Axis::Conformance, "settled_clean")
                .iter()
                .filter(|value| **value == 1.0)
                .count()
        })
        .sum::<usize>();
    let expected_cells = expected_cell_count();
    let expected_samples = expected_cells * 3;
    let _ = write!(
        out,
        "\n> **Qualification: {status}.** {}/{expected_cells} cells; {conformant_samples}/{expected_samples} conformant samples; exact source `{commit}`; source tree {}.\n",
        aggregates.len(),
        if clean { "clean" } else { "dirty or unknown" }
    );
}

fn expected_cell_count() -> usize {
    load_catalog()
        .expect("validated benchmark catalog")
        .into_iter()
        .map(|manifest| match manifest.topology {
            ScenarioTopology::Direct => 4,
            ScenarioTopology::Relay => 2,
        })
        .sum()
}

fn qualification_complete(aggregates: &[Aggregate]) -> bool {
    aggregates.len() == expected_cell_count()
        && aggregates
            .iter()
            .all(|item| item.samples == 3 && item.conformant() == Some(true))
}

fn render_machine_and_method(out: &mut String, host: &str) {
    out.push_str("\n## Machine and method\n\n");
    if let Some(descriptor) = load_host(host) {
        let cpu = descriptor.cpu_model.unwrap_or_else(|| "pending".into());
        let memory = descriptor
            .total_memory_bytes
            .map(|bytes| format!("{:.1} GiB", bytes as f64 / 1_073_741_824.0))
            .unwrap_or_else(|| "pending".into());
        let os = descriptor.os_version.unwrap_or_else(|| "pending".into());
        let cores = match (descriptor.physical_cores, descriptor.logical_cores) {
            (Some(physical), Some(logical)) => format!("{physical} physical / {logical} logical"),
            _ => "pending".into(),
        };
        let _ = writeln!(out, "{cpu}; {cores}; {memory}; {os}.\n");
    }
    out.push_str(
        "Release binaries run over loopback for 30 seconds per sample, three samples per cell. Endpoint scenarios cover all four initiator/responder pairings; relay scenarios cover both implementations behind the same fixed bidirectional wire driver. Default-policy rows preserve each implementation's normal TCP bitrate and MTU policy. The controlled 1 Gbps resource rows change only that interface policy, both for real endpoint transfers and for transported-resource switching; the tiny raw SINGLE relay scenario remains default-policy-only. Tables show median throughput and latency; memory is the maximum peak RSS. Energy is optional: it is metered processor energy minus a fresh idle baseline (macOS CPU Power; Linux RAPL package) and appears only when all three samples are positive. Packet/request energy is per delivery; resource energy is normalized per application MiB. Initiator/responder energy is the combined package measurement attributed by each role's CPU-time share. Relay-scenario package energy is explicitly whole-cell energy; only CPU and RSS are relay-isolated. A check means every sample satisfied the scenario's accounting rule.\n",
    );
}

#[derive(Clone)]
struct Aggregate {
    scenario: String,
    scenario_version: u32,
    subject: Subject,
    samples: usize,
    values: BTreeMap<(Axis, String), Vec<f64>>,
}

impl Aggregate {
    fn values(&self, axis: Axis, metric: &str) -> &[f64] {
        self.values
            .get(&(axis, metric.to_string()))
            .map(Vec::as_slice)
            .unwrap_or(&[])
    }

    fn median(&self, axis: Axis, metric: &str) -> Option<f64> {
        median(self.values(axis, metric))
    }

    fn sum(&self, axis: Axis, metric: &str) -> Option<f64> {
        let values = self.values(axis, metric);
        (!values.is_empty()).then(|| values.iter().sum())
    }

    fn maximum(&self, axis: Axis, metric: &str) -> Option<f64> {
        self.values(axis, metric).iter().copied().reduce(f64::max)
    }

    #[cfg(test)]
    fn energy(&self) -> Option<f64> {
        let values = self.values(Axis::Energy, "net_millijoules_per_delivered");
        (self.samples == 3 && values.len() == 3 && values.iter().all(|value| *value > 0.0))
            .then(|| median(values))
            .flatten()
    }

    fn role_energy(&self, metric: &str) -> Option<f64> {
        let values = self.values(Axis::Energy, metric);
        (self.samples == 3 && values.len() == 3 && values.iter().all(|value| *value > 0.0))
            .then(|| median(values))
            .flatten()
    }

    fn conformant(&self) -> Option<bool> {
        let values = self.values(Axis::Conformance, "settled_clean");
        (values.len() == self.samples).then(|| values.iter().all(|value| *value == 1.0))
    }
}

fn aggregate(rows: &[ResultRow]) -> Vec<Aggregate> {
    #[derive(Default)]
    struct Acc {
        scenario: String,
        version: u32,
        subject: Option<Subject>,
        samples: BTreeSet<u32>,
        values: BTreeMap<(Axis, String), Vec<f64>>,
    }
    let mut groups: BTreeMap<(String, String, String), Acc> = BTreeMap::new();
    for row in rows {
        let key = (
            row.scenario.clone(),
            row.subject.file_slug(),
            row.run_id.clone(),
        );
        let acc = groups.entry(key).or_default();
        acc.scenario = row.scenario.clone();
        acc.version = acc.version.max(row.scenario_version);
        acc.subject.get_or_insert_with(|| row.subject.clone());
        acc.samples.insert(row.sample_index);
        if let Some(value) = row.value {
            acc.values
                .entry((row.axis, row.metric.clone()))
                .or_default()
                .push(value);
        }
    }
    groups
        .into_values()
        .map(|acc| Aggregate {
            scenario: acc.scenario,
            scenario_version: acc.version,
            subject: acc.subject.expect("result group has a subject"),
            samples: acc.samples.len(),
            values: acc.values,
        })
        .collect()
}

fn median(values: &[f64]) -> Option<f64> {
    if values.is_empty() {
        return None;
    }
    let mut sorted = values.to_vec();
    sorted.sort_by(f64::total_cmp);
    let middle = sorted.len() / 2;
    Some(if sorted.len().is_multiple_of(2) {
        (sorted[middle - 1] + sorted[middle]) / 2.0
    } else {
        sorted[middle]
    })
}

fn render_headline(
    out: &mut String,
    aggregates: &[Aggregate],
    implementations: &[ImplementationDescriptor],
    qualification_complete: bool,
) {
    out.push_str("\n## At a glance\n\n| Scenario | Prns | Reference | Prns / reference |\n|---|---:|---:|---:|\n");
    for scenario_manifest in load_catalog().expect("validated benchmark catalog") {
        let scenario = scenario_manifest.name.as_str();
        let manifest = Manifest::load(scenario);
        let ours = comparison_subject(
            aggregates,
            scenario,
            "personal-rns",
            scenario_manifest.topology,
        );
        let reference = implementations
            .iter()
            .filter(|implementation| implementation.role == ImplementationRole::Reference)
            .find_map(|implementation| {
                comparison_subject(
                    aggregates,
                    scenario,
                    &implementation.slug,
                    scenario_manifest.topology,
                )
            });
        let ours_value = ours.and_then(|row| primary_value(row, &manifest));
        let reference_value = reference.and_then(|row| primary_value(row, &manifest));
        assert!(
            !qualification_complete || (ours_value.is_some() && reference_value.is_some()),
            "complete suite lacks the manifest-owned primary metric {} for {}",
            manifest.primary_metric,
            scenario,
        );
        let ratio = match (ours_value, reference_value) {
            (Some(ours), Some(reference)) if reference != 0.0 => {
                format!("{:.2}×", ours / reference)
            }
            _ => "—".into(),
        };
        let _ = writeln!(
            out,
            "| {} | {} | {} | {ratio} |",
            manifest.title,
            format_primary(ours_value, &manifest.primary_metric),
            format_primary(reference_value, &manifest.primary_metric),
        );
    }
    out.push_str(
        "\nA dash means no current three-sample release evidence is published for that scenario.\n",
    );
}

fn comparison_subject<'a>(
    aggregates: &'a [Aggregate],
    scenario: &str,
    implementation: &str,
    topology: ScenarioTopology,
) -> Option<&'a Aggregate> {
    aggregates.iter().find(|aggregate| {
        if aggregate.scenario != scenario {
            return false;
        }
        match (&aggregate.subject, topology) {
            (
                Subject::Direct {
                    initiator,
                    responder,
                    relay: None,
                },
                ScenarioTopology::Direct,
            ) => initiator == implementation && responder == implementation,
            (
                Subject::Direct {
                    initiator,
                    responder,
                    relay: Some(relay),
                },
                ScenarioTopology::Relay,
            ) => {
                initiator == "benchmark-wire-driver"
                    && responder == "benchmark-wire-driver"
                    && relay == implementation
            }
            _ => false,
        }
    })
}

fn primary_value(aggregate: &Aggregate, manifest: &Manifest) -> Option<f64> {
    let axis = match manifest.primary_metric.as_str() {
        "rtt_p50_ms" => Axis::Latency,
        "route_survived" => Axis::Conformance,
        metric if metric.contains("bytes_per_sec") => Axis::Throughput,
        _ => Axis::Throughput,
    };
    aggregate.median(axis, &manifest.primary_metric)
}

fn render_scenario(
    out: &mut String,
    manifest: &Manifest,
    rows: &[&Aggregate],
    implementations: &[ImplementationDescriptor],
) {
    let version = rows
        .iter()
        .map(|row| row.scenario_version)
        .max()
        .unwrap_or(manifest.version);
    let _ = write!(
        out,
        "\n#### {} (v{version})\n\n{}\n\n",
        manifest.title, manifest.summary
    );
    if manifest.topology == ScenarioTopology::Relay {
        render_transport_table(out, manifest, rows, implementations);
        render_manifest_notes(out, manifest, rows, implementations);
        return;
    }

    let columns = Columns::for_rows(rows);
    out.push_str("| Subject | Conformance");
    if columns.rate {
        out.push_str(" | Rate");
    }
    if columns.goodput {
        out.push_str(" | Goodput");
    }
    if columns.latency {
        out.push_str(" | RTT p50 / p99");
    }
    if columns.memory {
        out.push_str(" | Peak RSS (i / r)");
    }
    if columns.energy {
        if manifest.energy_per_mib() {
            out.push_str(" | Energy / MiB (i / r)");
        } else {
            out.push_str(" | Energy / delivery (i / r)");
        }
    }
    out.push_str(" |\n|---|---:");
    for enabled in [
        columns.rate,
        columns.goodput,
        columns.latency,
        columns.memory,
        columns.energy,
    ] {
        if enabled {
            out.push_str("|---:");
        }
    }
    out.push_str("|\n");

    let mut sorted = rows.to_vec();
    sorted.sort_by(|left, right| {
        throughput_value(right)
            .total_cmp(&throughput_value(left))
            .then_with(|| left.subject.file_slug().cmp(&right.subject.file_slug()))
    });
    for row in sorted {
        let _ = write!(
            out,
            "| {} | {}",
            annotated_subject_label(&row.subject, manifest, implementations),
            conformance_cell(row)
        );
        if columns.rate {
            let _ = write!(
                out,
                " | {}",
                rate_cell(
                    row.median(Axis::Throughput, "delivered_per_sec")
                        .or_else(|| row.median(Axis::Throughput, "requests_per_sec"))
                        .or_else(|| row.median(Axis::Throughput, "cycles_per_sec"))
                )
            );
        }
        if columns.goodput {
            let _ = write!(
                out,
                " | {}",
                bytes_cell(row.median(Axis::Throughput, "goodput_bytes_per_sec"))
            );
        }
        if columns.latency {
            let _ = write!(
                out,
                " | {}",
                latency_cell(
                    row.median(Axis::Latency, "rtt_p50_ms"),
                    row.median(Axis::Latency, "rtt_p99_ms")
                )
            );
        }
        if columns.memory {
            let _ = write!(
                out,
                " | {}",
                role_pair_cell(
                    row.maximum(Axis::Memory, "initiator_peak_rss_bytes"),
                    row.maximum(Axis::Memory, "responder_peak_rss_bytes"),
                    |bytes| format!("{:.1} MiB", bytes / 1_048_576.0),
                )
            );
        }
        if columns.energy {
            let role_energy = |role: &str| {
                if manifest.energy_per_mib() {
                    row.role_energy(&format!("{role}_net_millijoules_per_mebibyte"))
                        .or_else(|| {
                            let payload_mib = manifest.payload_len as f64 / 1_048_576.0;
                            (payload_mib > 0.0)
                                .then(|| {
                                    row.role_energy(&format!(
                                        "{role}_net_millijoules_per_delivered"
                                    ))
                                    .map(|value| value / payload_mib)
                                })
                                .flatten()
                        })
                } else {
                    row.role_energy(&format!("{role}_net_millijoules_per_delivered"))
                }
            };
            let _ = write!(
                out,
                " | {}",
                role_pair_cell(
                    role_energy("initiator"),
                    role_energy("responder"),
                    |value| {
                        if manifest.energy_per_mib() {
                            format!("{value:.2} mJ/MiB")
                        } else {
                            format!("{value:.2} mJ")
                        }
                    },
                )
            );
        }
        out.push_str(" |\n");
    }
    render_manifest_notes(out, manifest, rows, implementations);
}

fn render_manifest_notes(
    out: &mut String,
    manifest: &Manifest,
    rows: &[&Aggregate],
    implementations: &[ImplementationDescriptor],
) {
    let visible_cell_notes = manifest
        .cell_notes
        .iter()
        .enumerate()
        .filter(|(_, note)| rows.iter().any(|row| row.subject == note.subject))
        .collect::<Vec<_>>();
    if !visible_cell_notes.is_empty() {
        out.push_str("\n**Cell context**\n");
        for (index, note) in visible_cell_notes {
            let _ = writeln!(
                out,
                "\n{}. **{}** — {}",
                index + 1,
                subject_label(&note.subject, implementations),
                note.text
            );
        }
    }
    for note in &manifest.notes {
        let _ = writeln!(out, "\n> {note}");
    }
}

fn render_transport_table(
    out: &mut String,
    manifest: &Manifest,
    rows: &[&Aggregate],
    implementations: &[ImplementationDescriptor],
) {
    out.push_str(
        "| Relay | TCP policy / MTU | Link MTU / payload | Conformance | Payload | Frames | Wire in / out | Relay CPU | Relay peak RSS | Harness headroom |\n\
         |---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n",
    );
    let mut sorted = rows.to_vec();
    sorted.sort_by(|left, right| {
        throughput_value(right)
            .total_cmp(&throughput_value(left))
            .then_with(|| left.subject.file_slug().cmp(&right.subject.file_slug()))
    });
    for row in sorted {
        let wire = match (
            row.median(Axis::Throughput, "ingress_wire_bytes_per_sec"),
            row.median(Axis::Throughput, "egress_wire_bytes_per_sec"),
        ) {
            (Some(ingress), Some(egress)) => {
                format!(
                    "{} / {}",
                    bytes_cell(Some(ingress)),
                    bytes_cell(Some(egress))
                )
            }
            _ => "—".into(),
        };
        let headroom = match (
            row.median(Axis::Throughput, "harness_carried_payload_bytes_per_sec"),
            row.median(Axis::Throughput, "carried_payload_bytes_per_sec"),
            row.median(Axis::Conformance, "harness_headroom"),
        ) {
            (Some(harness), Some(carried), Some(1.0)) if carried > 0.0 => {
                format!("{:.2}×", harness / carried)
            }
            _ => "—".into(),
        };
        let tcp_policy = match (
            row.median(Axis::Conformance, "relay_bitrate_bps"),
            row.median(Axis::Conformance, "relay_mtu_bytes"),
        ) {
            (Some(bitrate), Some(mtu)) => {
                format!("{} / {:.0} KiB", bitrate_cell(bitrate), mtu / 1024.0)
            }
            _ => "—".into(),
        };
        let link_shape = match (
            row.median(Axis::Conformance, "negotiated_link_mtu_bytes"),
            row.median(Axis::Conformance, "resource_payload_bytes_per_frame"),
        ) {
            (Some(mtu), Some(payload)) => {
                format!("{:.0} / {:.0} KiB", mtu / 1024.0, payload / 1024.0)
            }
            _ => "—".into(),
        };
        let _ = writeln!(
            out,
            "| {} | {tcp_policy} | {link_shape} | {} | {} | {} | {wire} | {} | {} | {headroom} |",
            annotated_subject_label(&row.subject, manifest, implementations),
            conformance_cell(row),
            bytes_cell(row.median(Axis::Throughput, "carried_payload_bytes_per_sec")),
            rate_cell(row.median(Axis::Throughput, "forwarded_frames_per_sec")),
            row.median(Axis::Energy, "relay_cpu_seconds")
                .map(|value| format!("{value:.2} s"))
                .unwrap_or_else(|| "—".into()),
            row.maximum(Axis::Memory, "relay_peak_rss_bytes")
                .map(|value| format!("{:.1} MiB", value / 1_048_576.0))
                .unwrap_or_else(|| "—".into()),
        );
    }
}

fn bitrate_cell(bps: f64) -> String {
    if bps >= 1_000_000_000.0 {
        format!("{:.0} Gbps", bps / 1_000_000_000.0)
    } else {
        format!("{:.0} Mbps", bps / 1_000_000.0)
    }
}

#[derive(Default)]
struct Columns {
    rate: bool,
    goodput: bool,
    latency: bool,
    memory: bool,
    energy: bool,
}

impl Columns {
    fn for_rows(rows: &[&Aggregate]) -> Self {
        let has = |axis, metrics: &[&str]| {
            rows.iter().any(|row| {
                metrics
                    .iter()
                    .any(|metric| !row.values(axis, metric).is_empty())
            })
        };
        Self {
            rate: has(
                Axis::Throughput,
                &[
                    "delivered_per_sec",
                    "requests_per_sec",
                    "cycles_per_sec",
                    "forwarded_frames_per_sec",
                ],
            ),
            goodput: has(Axis::Throughput, &["goodput_bytes_per_sec"]),
            latency: has(Axis::Latency, &["rtt_p50_ms", "rtt_p99_ms"]),
            memory: has(
                Axis::Memory,
                &["initiator_peak_rss_bytes", "responder_peak_rss_bytes"],
            ),
            energy: rows.iter().any(|row| {
                row.role_energy("initiator_net_millijoules_per_delivered")
                    .or_else(|| row.role_energy("responder_net_millijoules_per_delivered"))
                    .is_some()
            }),
        }
    }
}

fn subject_label(subject: &Subject, implementations: &[ImplementationDescriptor]) -> String {
    let label = |slug: &str| {
        implementations
            .iter()
            .find(|implementation| implementation.slug == slug)
            .map(|implementation| implementation.implementation.clone())
            .unwrap_or_else(|| slug.to_string())
    };
    match subject {
        Subject::Direct {
            initiator,
            responder,
            relay: None,
        } => format!("{} → {}", label(initiator), label(responder)),
        Subject::Direct {
            initiator,
            responder,
            relay: Some(relay),
        } if initiator == "benchmark-wire-driver" && responder == "benchmark-wire-driver" => {
            format!("{} relay", label(relay))
        }
        Subject::Direct {
            initiator,
            responder,
            relay: Some(relay),
        } => format!(
            "{} → {} via {}",
            label(initiator),
            label(responder),
            label(relay)
        ),
    }
}

fn annotated_subject_label(
    subject: &Subject,
    manifest: &Manifest,
    implementations: &[ImplementationDescriptor],
) -> String {
    let label = subject_label(subject, implementations);
    manifest
        .cell_notes
        .iter()
        .position(|note| &note.subject == subject)
        .map_or(label.clone(), |index| {
            format!("{label}<sup>{}</sup>", index + 1)
        })
}

fn throughput_value(row: &Aggregate) -> f64 {
    row.median(Axis::Throughput, "delivered_per_sec")
        .or_else(|| row.median(Axis::Throughput, "requests_per_sec"))
        .or_else(|| row.median(Axis::Throughput, "cycles_per_sec"))
        .or_else(|| row.median(Axis::Throughput, "carried_payload_bytes_per_sec"))
        .or_else(|| row.median(Axis::Throughput, "goodput_bytes_per_sec"))
        .unwrap_or(f64::NEG_INFINITY)
}

fn role_pair_cell(
    initiator: Option<f64>,
    responder: Option<f64>,
    format: impl Fn(f64) -> String,
) -> String {
    match (initiator, responder) {
        (Some(initiator), Some(responder)) => {
            format!("i {} / r {}", format(initiator), format(responder))
        }
        (Some(initiator), None) => format!("i {} / r —", format(initiator)),
        (None, Some(responder)) => format!("i — / r {}", format(responder)),
        (None, None) => "—".into(),
    }
}

fn conformance_cell(row: &Aggregate) -> String {
    let delivered = row.sum(Axis::Conformance, "delivered");
    let sent = row.sum(Axis::Conformance, "sent");
    let culled = row
        .sum(Axis::Conformance, "locally_culled")
        .filter(|value| *value > 0.0)
        .map(|value| format!(" · {} local backpressure", integer(value)))
        .unwrap_or_default();
    match row.conformant() {
        Some(clean) => {
            let icon = if clean { PASS_ICON } else { FAIL_ICON };
            match (delivered, sent) {
                (Some(delivered), Some(sent)) => format!(
                    "{icon} {}/{} · {}/{} samples{culled}",
                    integer(delivered),
                    integer(sent),
                    row.values(Axis::Conformance, "settled_clean")
                        .iter()
                        .filter(|value| **value == 1.0)
                        .count(),
                    row.samples
                ),
                _ => format!(
                    "{icon} {}/{} samples",
                    row.values(Axis::Conformance, "settled_clean")
                        .iter()
                        .filter(|value| **value == 1.0)
                        .count(),
                    row.samples
                ),
            }
        }
        None => "—".into(),
    }
}

fn format_primary(value: Option<f64>, metric: &str) -> String {
    match metric {
        "rtt_p50_ms" => value
            .map(|value| format!("{value:.2} ms"))
            .unwrap_or_else(|| "—".into()),
        metric if metric.contains("bytes_per_sec") => bytes_cell(value),
        _ => rate_cell(value),
    }
}

fn rate_cell(value: Option<f64>) -> String {
    value
        .map(|value| format!("{}/s", humanize(value)))
        .unwrap_or_else(|| "—".into())
}

fn bytes_cell(value: Option<f64>) -> String {
    value
        .map(|value| {
            if value >= 1e6 {
                format!("{:.2} MB/s", value / 1e6)
            } else {
                format!("{:.1} kB/s", value / 1e3)
            }
        })
        .unwrap_or_else(|| "—".into())
}

fn latency_cell(p50: Option<f64>, p99: Option<f64>) -> String {
    match (p50, p99) {
        (Some(p50), Some(p99)) => {
            format!("{} / {} ms", latency_value(p50), latency_value(p99))
        }
        (Some(p50), None) => format!("{} ms", latency_value(p50)),
        _ => "—".into(),
    }
}

fn latency_value(value: f64) -> String {
    if value == 0.0 {
        "<1.00".into()
    } else {
        format!("{value:.2}")
    }
}

fn humanize(value: f64) -> String {
    if value >= 1e6 {
        format!("{:.2}M", value / 1e6)
    } else if value >= 1e3 {
        format!("{:.1}k", value / 1e3)
    } else if value < 1.0 {
        format!("{value:.2}")
    } else {
        format!("{value:.0}")
    }
}

fn integer(value: f64) -> String {
    format!("{:.0}", value)
}

fn render_legends(
    out: &mut String,
    aggregates: &[Aggregate],
    implementations: &[ImplementationDescriptor],
) {
    let mut used = BTreeSet::new();
    for aggregate in aggregates {
        match &aggregate.subject {
            Subject::Direct {
                initiator,
                responder,
                relay,
            } => {
                used.insert(initiator.clone());
                used.insert(responder.clone());
                if let Some(relay) = relay {
                    used.insert(relay.clone());
                }
            }
        }
    }
    out.push_str("\n## Implementation legend\n");
    for slug in used {
        if let Some(implementation) = implementations
            .iter()
            .find(|implementation| implementation.slug == slug)
        {
            let reference = if implementation.role == ImplementationRole::Reference {
                "; reference"
            } else {
                ""
            };
            let _ = writeln!(
                out,
                "\n- **{}** — {}, {}{}.",
                implementation.implementation,
                implementation.language,
                implementation.crypto_backend,
                reference
            );
        }
    }
    out.push_str("\n## Metric legend\n\nConformance is clean samples and exact delivered/sent accounting. Rows are ordered by median throughput, never by memory or energy. Rate is median settled operations per second. Goodput is median application bytes per second. Relay scenarios report carried opaque payload bytes, forwarded frames, HDLC-framed TCP wire rates, relay-only CPU/RSS, and direct-driver headroom; transported-resource rows additionally expose negotiated link MTU and payload bytes per part. RTT is median p50/p99 settlement latency. Peak RSS shows the largest initiator (`i`) and responder (`r`) process peaks across samples. Energy shows optional initiator/responder attribution of median net processor energy and appears only with three positive-baseline samples: per delivery for packets/requests, per application MiB for resources. Relay-scenario energy is whole-cell package energy, never relay-only energy.\n");
}

struct Manifest {
    version: u32,
    title: String,
    category: String,
    summary: String,
    primary_metric: String,
    payload_len: u64,
    notes: Vec<String>,
    cell_notes: Vec<ScenarioCellNote>,
    topology: ScenarioTopology,
}

impl Manifest {
    fn energy_per_mib(&self) -> bool {
        self.primary_metric.contains("bytes_per_sec")
    }

    fn exists(scenario: &str) -> bool {
        scenario_dir(scenario).join("manifest.json").is_file()
    }

    fn load(scenario: &str) -> Self {
        let path = scenario_dir(scenario).join("manifest.json");
        let json: serde_json::Value = serde_json::from_str(
            &std::fs::read_to_string(&path)
                .unwrap_or_else(|error| panic!("read {}: {error}", path.display())),
        )
        .unwrap_or_else(|error| panic!("parse {}: {error}", path.display()));
        let strings = |key: &str| {
            json[key]
                .as_array()
                .map(|items| {
                    items
                        .iter()
                        .filter_map(|item| item.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default()
        };
        Self {
            version: json["version"].as_u64().unwrap_or(0) as u32,
            title: json["title"].as_str().unwrap_or(scenario).to_string(),
            category: json["category"].as_str().unwrap_or("Other").to_string(),
            summary: json["summary"].as_str().unwrap_or("").to_string(),
            primary_metric: json["primary_metric"]
                .as_str()
                .unwrap_or("delivered_per_sec")
                .to_string(),
            payload_len: json["profile"]["payload_len"].as_u64().unwrap_or(0),
            notes: strings("notes"),
            cell_notes: serde_json::from_value(json["cell_notes"].clone()).unwrap_or_default(),
            topology: serde_json::from_value(json["topology"].clone()).unwrap_or_default(),
        }
    }
}

