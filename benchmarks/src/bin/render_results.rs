fn render_transport_table(
    out: &mut String,
    manifest: &Manifest,
    rows: &[&Aggregate],
    implementations: &[ImplementationDescriptor],
) {
    out.push_str(
        "| Relay | TCP policy / MTU | Link MTU / payload | Conformance | Payload | Frames | Wire in / out | Relay CPU | Relay peak RSS | Harness source / sink / limit |\n\
         |---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n",
    );
    let mut sorted = rows.to_vec();
    sorted.sort_by(|left, right| {
        throughput_value(right)
            .total_cmp(&throughput_value(left))
            .then_with(|| left.subject.file_slug().cmp(&right.subject.file_slug()))
    });
    for row in sorted {
        let wire = match (
            row.median(Axis::Throughput, "ingress_wire_bytes_per_sec"),
            row.median(Axis::Throughput, "egress_wire_bytes_per_sec"),
        ) {
            (Some(ingress), Some(egress)) => {
                format!(
                    "{} / {}",
                    bytes_cell(Some(ingress)),
                    bytes_cell(Some(egress))
                )
            }
            _ => "—".into(),
        };
        let headroom = match (
            row.median(Axis::Throughput, "harness_source_payload_bytes_per_sec"),
            row.median(Axis::Throughput, "harness_sink_payload_bytes_per_sec"),
            row.median(Axis::Throughput, "harness_carried_payload_bytes_per_sec"),
            row.median(Axis::Throughput, "carried_payload_bytes_per_sec"),
            row.median(Axis::Conformance, "harness_headroom"),
        ) {
            (Some(source), Some(sink), Some(harness), Some(carried), Some(1.0))
                if carried > 0.0 =>
            {
                format!(
                    "{:.2}× / {:.2}× / {:.2}×",
                    source / carried,
                    sink / carried,
                    harness / carried
                )
            }
            _ => "—".into(),
        };
        let tcp_policy = match (
            row.median(Axis::Conformance, "relay_bitrate_bps"),
            row.median(Axis::Conformance, "relay_mtu_bytes"),
        ) {
            (Some(bitrate), Some(mtu)) => {
                format!("{} / {:.0} KiB", bitrate_cell(bitrate), mtu / 1024.0)
            }
            _ => "—".into(),
        };
        let link_shape = match (
            row.median(Axis::Conformance, "negotiated_link_mtu_bytes"),
            row.median(Axis::Conformance, "resource_payload_bytes_per_frame"),
        ) {
            (Some(mtu), Some(payload)) => {
                format!("{:.0} / {:.0} KiB", mtu / 1024.0, payload / 1024.0)
            }
            _ => "—".into(),
        };
        let _ = writeln!(
            out,
            "| {} | {tcp_policy} | {link_shape} | {} | {} | {} | {wire} | {} | {} | {headroom} |",
            annotated_subject_label(&row.subject, manifest, implementations),
            conformance_cell(row),
            bytes_cell(row.median(Axis::Throughput, "carried_payload_bytes_per_sec")),
            rate_cell(row.median(Axis::Throughput, "forwarded_frames_per_sec")),
            row.median(Axis::Energy, "relay_cpu_seconds")
                .map(|value| format!("{value:.2} s"))
                .unwrap_or_else(|| "—".into()),
            row.maximum(Axis::Memory, "relay_peak_rss_bytes")
                .map(|value| format!("{:.1} MiB", value / 1_048_576.0))
                .unwrap_or_else(|| "—".into()),
        );
    }
}

fn bitrate_cell(bps: f64) -> String {
    if bps >= 1_000_000_000.0 {
        format!("{:.0} Gbps", bps / 1_000_000_000.0)
    } else {
        format!("{:.0} Mbps", bps / 1_000_000.0)
    }
}

#[derive(Default)]
struct Columns {
    rate: bool,
    goodput: bool,
    latency: bool,
    memory: bool,
    energy: bool,
}

impl Columns {
    fn for_rows(rows: &[&Aggregate]) -> Self {
        let has = |axis, metrics: &[&str]| {
            rows.iter().any(|row| {
                metrics
                    .iter()
                    .any(|metric| !row.values(axis, metric).is_empty())
            })
        };
        Self {
            rate: has(
                Axis::Throughput,
                &[
                    "delivered_per_sec",
                    "requests_per_sec",
                    "cycles_per_sec",
                    "forwarded_frames_per_sec",
                ],
            ),
            goodput: has(Axis::Throughput, &["goodput_bytes_per_sec"]),
            latency: has(Axis::Latency, &["rtt_p50_ms", "rtt_p99_ms"]),
            memory: has(
                Axis::Memory,
                &["initiator_peak_rss_bytes", "responder_peak_rss_bytes"],
            ),
            energy: rows.iter().any(|row| {
                row.role_energy("initiator_net_millijoules_per_delivered")
                    .or_else(|| row.role_energy("responder_net_millijoules_per_delivered"))
                    .is_some()
            }),
        }
    }
}

fn subject_label(subject: &Subject, implementations: &[ImplementationDescriptor]) -> String {
    let label = |slug: &str| {
        implementations
            .iter()
            .find(|implementation| implementation.slug == slug)
            .map(|implementation| implementation.implementation.clone())
            .unwrap_or_else(|| slug.to_string())
    };
    match subject {
        Subject::Direct {
            initiator,
            responder,
            relay: None,
        } => format!("{} → {}", label(initiator), label(responder)),
        Subject::Direct {
            initiator,
            responder,
            relay: Some(relay),
        } if initiator == "benchmark-wire-driver" && responder == "benchmark-wire-driver" => {
            format!("{} relay", label(relay))
        }
        Subject::Direct {
            initiator,
            responder,
            relay: Some(relay),
        } => format!(
            "{} → {} via {}",
            label(initiator),
            label(responder),
            label(relay)
        ),
    }
}

fn annotated_subject_label(
    subject: &Subject,
    manifest: &Manifest,
    implementations: &[ImplementationDescriptor],
) -> String {
    let label = subject_label(subject, implementations);
    manifest
        .cell_notes
        .iter()
        .position(|note| &note.subject == subject)
        .map_or(label.clone(), |index| {
            format!("{label}<sup>{}</sup>", index + 1)
        })
}

fn throughput_value(row: &Aggregate) -> f64 {
    row.median(Axis::Throughput, "delivered_per_sec")
        .or_else(|| row.median(Axis::Throughput, "requests_per_sec"))
        .or_else(|| row.median(Axis::Throughput, "cycles_per_sec"))
        .or_else(|| row.median(Axis::Throughput, "carried_payload_bytes_per_sec"))
        .or_else(|| row.median(Axis::Throughput, "goodput_bytes_per_sec"))
        .unwrap_or(f64::NEG_INFINITY)
}

fn role_pair_cell(
    initiator: Option<f64>,
    responder: Option<f64>,
    format: impl Fn(f64) -> String,
) -> String {
    match (initiator, responder) {
        (Some(initiator), Some(responder)) => {
            format!("i {} / r {}", format(initiator), format(responder))
        }
        (Some(initiator), None) => format!("i {} / r —", format(initiator)),
        (None, Some(responder)) => format!("i — / r {}", format(responder)),
        (None, None) => "—".into(),
    }
}

fn conformance_cell(row: &Aggregate) -> String {
    let delivered = row.sum(Axis::Conformance, "delivered");
    let sent = row.sum(Axis::Conformance, "sent");
    let culled = row
        .sum(Axis::Conformance, "locally_culled")
        .filter(|value| *value > 0.0)
        .map(|value| format!(" · {} local backpressure", integer(value)))
        .unwrap_or_default();
    match row.conformant() {
        Some(clean) => {
            let icon = if clean { PASS_ICON } else { FAIL_ICON };
            match (delivered, sent) {
                (Some(delivered), Some(sent)) => format!(
                    "{icon} {}/{} · {}/{} samples{culled}",
                    integer(delivered),
                    integer(sent),
                    row.values(Axis::Conformance, "settled_clean")
                        .iter()
                        .filter(|value| **value == 1.0)
                        .count(),
                    row.samples
                ),
                _ => format!(
                    "{icon} {}/{} samples",
                    row.values(Axis::Conformance, "settled_clean")
                        .iter()
                        .filter(|value| **value == 1.0)
                        .count(),
                    row.samples
                ),
            }
        }
        None => "—".into(),
    }
}

fn format_primary(value: Option<f64>, metric: &str) -> String {
    match metric {
        "rtt_p50_ms" => value
            .map(|value| format!("{value:.2} ms"))
            .unwrap_or_else(|| "—".into()),
        metric if metric.contains("bytes_per_sec") => bytes_cell(value),
        _ => rate_cell(value),
    }
}

fn rate_cell(value: Option<f64>) -> String {
    value
        .map(|value| format!("{}/s", humanize(value)))
        .unwrap_or_else(|| "—".into())
}

fn bytes_cell(value: Option<f64>) -> String {
    value
        .map(|value| {
            if value >= 1e6 {
                format!("{:.2} MB/s", value / 1e6)
            } else {
                format!("{:.1} kB/s", value / 1e3)
            }
        })
        .unwrap_or_else(|| "—".into())
}

fn latency_cell(p50: Option<f64>, p99: Option<f64>) -> String {
    match (p50, p99) {
        (Some(p50), Some(p99)) => {
            format!("{} / {} ms", latency_value(p50), latency_value(p99))
        }
        (Some(p50), None) => format!("{} ms", latency_value(p50)),
        _ => "—".into(),
    }
}

fn latency_value(value: f64) -> String {
    if value == 0.0 {
        "<1.00".into()
    } else {
        format!("{value:.2}")
    }
}

fn humanize(value: f64) -> String {
    if value >= 1e6 {
        format!("{:.2}M", value / 1e6)
    } else if value >= 1e3 {
        format!("{:.1}k", value / 1e3)
    } else if value < 1.0 {
        format!("{value:.2}")
    } else {
        format!("{value:.0}")
    }
}

fn integer(value: f64) -> String {
    format!("{:.0}", value)
}

fn render_legends(
    out: &mut String,
    aggregates: &[Aggregate],
    implementations: &[ImplementationDescriptor],
) {
    let mut used = BTreeSet::new();
    for aggregate in aggregates {
        match &aggregate.subject {
            Subject::Direct {
                initiator,
                responder,
                relay,
            } => {
                used.insert(initiator.clone());
                used.insert(responder.clone());
                if let Some(relay) = relay {
                    used.insert(relay.clone());
                }
            }
        }
    }
    out.push_str("\n## Implementation legend\n");
    for slug in used {
        if let Some(implementation) = implementations
            .iter()
            .find(|implementation| implementation.slug == slug)
        {
            let reference = if implementation.role == ImplementationRole::Reference {
                "; reference"
            } else {
                ""
            };
            let _ = writeln!(
                out,
                "\n- **{}** — {}, {}{}.",
                implementation.implementation,
                implementation.language,
                implementation.crypto_backend,
                reference
            );
        }
    }
    out.push_str("\n## Metric legend\n\nConformance is clean samples and exact delivered/sent accounting. Rows are ordered by median throughput, never by memory or energy. Rate is median settled operations per second. Goodput is median application bytes per second. Relay scenarios report carried opaque payload bytes, forwarded frames, actual HDLC-framed TCP wire rates, relay-only CPU/RSS, and full-path driver source/sink/limiting headroom; transported-resource rows additionally expose negotiated link MTU and payload bytes per part. RTT is median p50/p99 settlement latency. Peak RSS shows the largest initiator (`i`) and responder (`r`) process peaks across samples. Energy shows optional initiator/responder attribution of median net processor energy and appears only with three positive-baseline samples: per delivery for packets/requests, per application MiB for resources. Relay-scenario energy is whole-cell package energy, never relay-only energy.\n");
}

struct Manifest {
    version: u32,
    title: String,
    category: String,
    summary: String,
    primary_metric: String,
    payload_len: u64,
    notes: Vec<String>,
    cell_notes: Vec<ScenarioCellNote>,
    topology: ScenarioTopology,
}

impl Manifest {
    fn energy_per_mib(&self) -> bool {
        self.primary_metric.contains("bytes_per_sec")
    }

    fn exists(scenario: &str) -> bool {
        scenario_dir(scenario).join("manifest.json").is_file()
    }

    fn load(scenario: &str) -> Self {
        let path = scenario_dir(scenario).join("manifest.json");
        let json: serde_json::Value = serde_json::from_str(
            &std::fs::read_to_string(&path)
                .unwrap_or_else(|error| panic!("read {}: {error}", path.display())),
        )
        .unwrap_or_else(|error| panic!("parse {}: {error}", path.display()));
        let strings = |key: &str| {
            json[key]
                .as_array()
                .map(|items| {
                    items
                        .iter()
                        .filter_map(|item| item.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default()
        };
        Self {
            version: json["version"].as_u64().unwrap_or(0) as u32,
            title: json["title"].as_str().unwrap_or(scenario).to_string(),
            category: json["category"].as_str().unwrap_or("Other").to_string(),
            summary: json["summary"].as_str().unwrap_or("").to_string(),
            primary_metric: json["primary_metric"]
                .as_str()
                .unwrap_or("delivered_per_sec")
                .to_string(),
            payload_len: json["profile"]["payload_len"].as_u64().unwrap_or(0),
            notes: strings("notes"),
            cell_notes: serde_json::from_value(json["cell_notes"].clone()).unwrap_or_default(),
            topology: serde_json::from_value(json["topology"].clone()).unwrap_or_default(),
        }
    }
}

